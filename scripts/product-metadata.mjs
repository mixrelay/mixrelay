import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

export function validateProductMetadata(metadata) {
  if (!metadata || !['publisher', 'email', 'homepage'].every(key => typeof metadata[key] === 'string')
    || !/^[A-Za-z][A-Za-z .-]+$/.test(metadata.publisher)
    || !/^[a-z0-9.+-]+@[a-z0-9.-]+\.[a-z]{2,}$/.test(metadata.email)
    || !/^https:\/\/[a-z0-9.-]+\/[a-z0-9/-]+$/.test(metadata.homepage)) {
    throw new Error('Invalid public product metadata');
  }
}

export const productContact = metadata => `${metadata.publisher} <${metadata.email}>`;

/** Checked-in package fields are generated by support:sync from the support contract. */
export function syncProductMetadata(metadata, root, write = false) {
  validateProductMetadata(metadata);
  const update = (name, transform) => {
    const path = resolve(root, name);
    const current = readFileSync(path, 'utf8');
    const expected = transform(current);
    if (write) writeFileSync(path, expected);
    else if (current !== expected) throw new Error(`Product metadata drift: ${name}; run pnpm support:sync`);
  };
  for (const name of ['package.json', 'apps/desktop/package.json', 'apps/control-ui/package.json', 'apps/streamdeck-plugin/package.json']) {
    update(name, text => {
      const value = JSON.parse(text);
      value.author = productContact(metadata);
      value.homepage = metadata.homepage;
      delete value.repository;
      return `${JSON.stringify(value, null, 2)}\n`;
    });
  }
  update('Cargo.toml', text => {
    if (!/^authors = .*$/m.test(text) || !/^homepage = .*$/m.test(text)) {
      throw new Error('Cargo.toml must declare workspace authors and homepage');
    }
    return text.replace(/^authors = .*$/m, `authors = ["${productContact(metadata)}"]`)
      .replace(/^homepage = .*$/m, `homepage = "${metadata.homepage}"`);
  });
  update('apps/desktop/src-tauri/tauri.conf.json', text => {
    const value = JSON.parse(text);
    value.bundle.publisher = metadata.publisher;
    value.bundle.homepage = metadata.homepage;
    return `${JSON.stringify(value, null, 2)}\n`;
  });
}
